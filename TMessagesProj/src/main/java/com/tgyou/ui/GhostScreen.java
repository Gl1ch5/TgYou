package com.tgyou.ui;

import com.tgyou.plugins.GhostModePlugin;

/** «Режим Призрака»: список опций с мастер-переключателем и зафиксированными значениями. */
public class GhostScreen extends TgYouScreen {

    @Override
    protected String screenTitle() {
        return "Режим Призрака";
    }

    @Override
    protected void build() {
        master("ghost", "Режим призрака", GhostModePlugin.OPTION_KEYS, new String[]{
                "Не читать сообщения",
                "Не читать истории",
                "Не отправлять «онлайн»",
                "Не отправлять «печатает»",
                "Автоматический «офлайн»"}, null);
        info("Зажмите любую опцию, чтобы зафиксировать её значение.");

        toggle(GhostModePlugin.READ_ON_ACTION, "Читать при действиях",
                "Автоматически читает сообщение при отправке нового или при реакции. Работает только вместе с «Не читать сообщения».", false);
        toggle(GhostModePlugin.DELAY, "Использовать отложку",
                "Автоматически ставит задержку в ~12 секунд при отправке сообщений. "
                        + "При использовании этой функции вы не будете появляться в сети. Не рекомендуется использовать на слабом интернете.", false);
        gap();
        choice(GhostModePlugin.SILENT, "Отправлять без звука", null, 0, "Никогда", "Всегда", "В режиме призрака");
        info("Отправляет сообщения по умолчанию без звука.");
        toggle(GhostModePlugin.STORY_SUGGEST, "Предлагать призрака для сторис",
                "Показывает предупреждение перед открытием сторис, предлагая включить режим призрака.", false);
        gap();
    }
}
